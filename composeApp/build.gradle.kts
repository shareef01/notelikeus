compose.desktop {
    application {
        mainClass = "com.aus.notelikeus.MainKt"

        nativeDistributions {
            // Windows only. DesktopTokenStore encrypts the session with DPAPI through JNA
            // (Crypt32), which compiles everywhere but throws UnsatisfiedLinkError on first use
            // on macOS/Linux — so shipping Dmg and Deb produced installers whose sign-in could
            // not work. Restore those formats alongside a Keychain/libsecret backend.
            targetFormats(TargetFormat.Msi)
            packageName = "Notelikeus"
            packageVersion = "1.0.0"
            description = "Elite Cross-Platform Note Taking"
            copyright = "© 2026 Aus"
            vendor = "Aus"

            // jlink builds the packaged runtime from this list, so anything reached only
            // reflectively has to be named explicitly. All four fail *only* in the MSI —
            // `./gradlew run` has the full JDK on hand and hides every one of them.
            // jlink builds the packaged runtime from this list. Without it the image resolves to
            // 7 modules and omits the first three below, so the MSI fails at runtime while
            // `./gradlew run` — which has the whole JDK on hand — stays green. Verified by
            // diffing `runtime/release` in the generated app image with and without this block.
            modules(
                "java.net.http",    // HttpClient: Firestore transport, token refresh, sign-in
                "jdk.unsupported",  // sun.misc.Unsafe, via datastore-protobuf
                "java.naming",      // reached from the TLS stack
                // Present by default on the current JDK, named anyway so a JDK change cannot
                // silently drop EC and break the handshake with accounts.google.com.
                "jdk.crypto.ec"
            )

            windows {
                shortcut = true
                menu = true
                upgradeUuid = "d738f712-4217-485c-9c71-0816999b7082"
            }
        }
    }
}

