/**
 * A build input from the environment, else from the gitignored `local.properties`; empty when
 * neither has it.
 */
fun localOrEnv(envName: String, propertyName: String): String {
    System.getenv(envName)?.trim()?.takeIf { it.isNotEmpty() }?.let { return it }
    val file = rootProject.file("local.properties")
    if (!file.exists()) return ""
    return Properties()
        .apply { file.inputStream().use { stream -> load(stream) } }
        .getProperty(propertyName)
        ?.trim()
        .orEmpty()
}

fun quotedBuildConfig(value: String): String {
    val escaped = value.replace("\\", "\\\\").replace("\"", "\\\"")
    return "\"$escaped\""
}

/**
 * The hosted backend every client build talks to: Supabase project URL, its public anon key, and
 * the attachments Worker. Android compiles these into BuildConfig; desktop into the generated
 * [generateDesktopBackendConfig] object below. Both read the same env vars / `local.properties`
 * keys, so a release that is built without them has sign-in and sync switched off.
 */
val backendUrl: String = localOrEnv("NOTELIKEUS_SUPABASE_URL", "notelikeus.supabaseUrl")
val backendAnonKey: String = localOrEnv("NOTELIKEUS_SUPABASE_ANON_KEY", "notelikeus.supabaseAnonKey")
val backendWorkerUrl: String =
    localOrEnv("NOTELIKEUS_ATTACHMENTS_WORKER_URL", "notelikeus.attachmentsWorkerUrl")
/**
 * The web app's Turnstile challenge page (`web/captcha.html`, D30), e.g.
 * `https://<pages host>/captcha.html`. Empty: sign-in asks for no CAPTCHA, as the local
 * Supabase stack expects.
 */
val backendCaptchaPageUrl: String =
    localOrEnv("NOTELIKEUS_CAPTCHA_PAGE_URL", "notelikeus.captchaPageUrl")

/** Kotlin string literal body: no quote, backslash or `$` template can escape into code. */
fun kotlinStringBody(value: String): String =
    value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")

/**
 * The desktop backend, compiled in. A packaged MSI has no environment variables and no
 * `local.properties`, so without this it shipped with sync off. BackendConfig.desktop prefers these
 * values over a `local.properties` it finds on disk, so a stray file cannot redirect a release.
 */
val generateDesktopBackendConfig by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/desktopBackend/kotlin")
    // Escaped here, at configuration time: the task action may not call back into this script.
    val url = kotlinStringBody(backendUrl)
    val anonKey = kotlinStringBody(backendAnonKey)
    val workerUrl = kotlinStringBody(backendWorkerUrl)
    val captchaPageUrl = kotlinStringBody(backendCaptchaPageUrl)
    inputs.property("supabaseUrl", url)
    inputs.property("supabaseAnonKey", anonKey)
    inputs.property("attachmentsWorkerUrl", workerUrl)
    inputs.property("captchaPageUrl", captchaPageUrl)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().asFile.resolve("com/aus/notelikeus/data/remote/CompiledBackendConfig.kt")
        file.parentFile.mkdirs()
        file.writeText(
            """
            // Generated by the `generateDesktopBackendConfig` Gradle task. Do not edit or commit.
            package com.aus.notelikeus.data.remote

            internal object CompiledBackendConfig {
                const val SUPABASE_URL: String = "$url"
                const val SUPABASE_ANON_KEY: String = "$anonKey"
                const val ATTACHMENTS_WORKER_URL: String = "$workerUrl"
                const val CAPTCHA_PAGE_URL: String = "$captchaPageUrl"
            }

            """.trimIndent()
        )
    }
}

/**
 * Fails a store or installer build that has no hosted backend. Debug, test and CI branch builds stay
 * free to build without one; only the artifacts users install (the Android App Bundle and the MSI)
 * depend on this check, so a missing secret stops the release instead of shipping it without sync.
 */
val verifyReleaseBackendConfig by tasks.registering {
    val url = backendUrl
    val anonKey = backendAnonKey
    val workerUrl = backendWorkerUrl
    val captchaPageUrl = backendCaptchaPageUrl
    inputs.property("supabaseUrl", url)
    inputs.property("supabaseAnonKey", anonKey)
    inputs.property("attachmentsWorkerUrl", workerUrl)
    inputs.property("captchaPageUrl", captchaPageUrl)
    doLast {
        val problems = buildList {
            if (!url.startsWith("https://")) add("NOTELIKEUS_SUPABASE_URL must be a hosted https URL")
            if (!anonKey.startsWith("eyJ")) add("NOTELIKEUS_SUPABASE_ANON_KEY must be the public anon JWT (eyJ...)")
            if (!workerUrl.startsWith("https://")) add("NOTELIKEUS_ATTACHMENTS_WORKER_URL must be a hosted https URL")
            // The hosted project requires Turnstile on code requests (D30); without the page a
            // release could not sign anyone in once that is on.
            if (!captchaPageUrl.startsWith("https://")) add("NOTELIKEUS_CAPTCHA_PAGE_URL must be the hosted https captcha page")
        }
        if (problems.isNotEmpty()) {
            throw GradleException(
                "This release would ship without cloud sync: " + problems.joinToString("; ") +
                    ". Set the environment variables or the notelikeus.* keys in local.properties.",
            )
        }
    }
}

tasks.matching { it.name.startsWith("package") && it.name.endsWith("Msi") }.configureEach {
    dependsOn(verifyReleaseBackendConfig)
}

// Gradle's default failure line is the exception's class name and one frame. That hides exactly what a
// flaky UncaughtExceptionsBeforeTest needs: the leaked exception from an earlier test rides along as a
// suppressed exception, and only the full format with causes prints it.
tasks.withType<Test>().configureEach {
    testLogging {
        events(TestLogEvent.FAILED)
        exceptionFormat = TestExceptionFormat.FULL
        showExceptions = true
        showCauses = true
        showStackTraces = true
    }
}

/**
 * The app version, compiled into commonMain so both [AppConfig] actuals read one value.
 *
 * Sourced from `notelikeus.versionName` in gradle.properties, which androidApp's `versionName`
 * reads too — so the number the build stamps on the APK and the number the UI shows cannot drift.
 */
val appVersionName: String = providers.gradleProperty("notelikeus.versionName").get()

val generateAppVersion by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/appVersion/kotlin")
    val version = appVersionName
    inputs.property("versionName", version)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().asFile.resolve("com/aus/notelikeus/util/GeneratedAppVersion.kt")
        file.parentFile.mkdirs()
        file.writeText(
            """
            // Generated by the `generateAppVersion` Gradle task. Do not edit or commit.
            package com.aus.notelikeus.util

            internal const val GENERATED_APP_VERSION_NAME: String = "$version"

            """.trimIndent()
        )
    }
}

