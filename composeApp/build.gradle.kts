/**
 * The desktop OAuth client secret, baked in at build time.
 *
 * DesktopOAuthConfig resolves the secret at runtime from the environment or `local.properties`,
 * which covers development but leaves a packaged app with nothing: the end user has neither. So
 * the same value is also compiled in here, as the last fallback in that chain.
 *
 * Read from `NOTELIKEUS_OAUTH_CLIENT_SECRET`, or `notelikeus.oauthClientSecret` in the gitignored
 * `local.properties`. Absent (CI, a fresh clone) it compiles to an empty string and only desktop
 * Google sign-in is unavailable — everything else builds and tests normally.
 *
 * Note this puts the secret in the shipped binary. Google classes installed-app secrets as
 * non-confidential (RFC 8252 — PKCE is what secures this flow), so that is the accepted trade;
 * what matters is that it stays out of version control.
 */
val oauthClientSecret: String =
    System.getenv("NOTELIKEUS_OAUTH_CLIENT_SECRET")
        ?: rootProject.file("local.properties").takeIf { it.exists() }?.let { file ->
            Properties()
                .apply { file.inputStream().use { stream -> load(stream) } }
                .getProperty("notelikeus.oauthClientSecret")
        }
        ?: ""

val generateDesktopSecrets by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/desktopSecrets/kotlin")
    val secret = oauthClientSecret
    inputs.property("oauthClientSecret", secret)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().asFile.resolve("com/aus/notelikeus/di/DesktopSecrets.kt")
        file.parentFile.mkdirs()
        // Escape so a quote/backslash in the environment variable cannot break the generated
        // Kotlin (or smuggle code into it) — the build must fail loudly on weird input instead.
        val escapedSecret = secret.replace("\\", "\\\\").replace("\"", "\\\"")
        file.writeText(
            """
            // Generated by the `generateDesktopSecrets` Gradle task. Do not edit or commit.
            package com.aus.notelikeus.di

            internal object DesktopSecrets {
                const val OAUTH_CLIENT_SECRET: String = "$escapedSecret"
            }

            """.trimIndent()
        )
    }
}

